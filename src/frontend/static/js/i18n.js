export let currentLang = localStorage.getItem("jarvis_lang") || "es";

export function setLanguage(lang, { persist = true } = {}) {
    if (translations[lang]) {
        currentLang = lang;
        if (persist) localStorage.setItem("jarvis_lang", lang);
        document.documentElement.lang = lang;
        updateUI();
    }
}

export function t(key) {
    return translations[currentLang][key] || translations["en"][key] || key;
}

export function updateUI() {
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (el.tagName === "INPUT" && el.hasAttribute("placeholder")) {
            el.placeholder = t(key);
        } else if (el.hasAttribute("data-text")) {
            const val = t(key);
            el.setAttribute("data-text", val);
            el.textContent = val;
        } else {
            el.textContent = t(key);
        }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach(el => {
        el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria-label")));
    });
}
